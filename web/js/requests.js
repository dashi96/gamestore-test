/**
 * Пропуск для ответов сервера.
 *
 * Пункт 5.2 ТЗ: устаревшие ответы не перетирают более свежие. Отменой запроса
 * это не решается — отмена не мгновенна, и ответ на уже отменённый запрос
 * вполне может дойти. Не решается и временем: два ответа приходят в одну
 * миллисекунду, а порядок отправки при этом известен точно.
 *
 * Поэтому решает номер. Каждый запрос берёт талон, применяется только ответ с
 * талоном больше последнего применённого. Логика отдельным модулем намеренно:
 * так её проверяет `node --test`, без браузера и без сети.
 */
export function createGate() {
  let issued = 0
  let applied = 0

  return {
    /** Талон для нового запроса. */
    next: () => ++issued,

    /** @returns true — ответ свежее всех применённых; false — отбросить. */
    accept(ticket) {
      if (!Number.isInteger(ticket) || ticket <= applied) return false
      applied = ticket
      return true
    },

    stats: () => ({ issued, applied }),
  }
}
